import CustomButton from "@/app/components/common/CustomButton";
import CustomSelect from "@/app/components/common/CustomSelect";
import CustomTextField from "@/app/components/common/CustomTextfield";
import {
  Box,
  Divider,
  Drawer,
  SelectChangeEvent,
  Stack,
  Typography,
} from "@mui/material";
import React, { useState } from "react";
import { Role } from "../manageData";
import CustomCheckbox from "@/app/components/common/CustomCheckBox";
import PasswordField from "@/app/components/common/CustomPassword";
import { useForm, Controller } from "react-hook-form";
import { apiCall } from "@/app/utils/APIUtils";

interface FormValues {
  first_name: string;
  last_name: string;
  email: string;
  password: string;
  user_type: string;
}

const AddCustomerDrawer: React.FC<any> = ({
  open,
  handleClose,
  onCustomerAdded
}) => {
  const [isPasswordAutoGenerated, setIsPasswordAutoGenerated] = useState(false);
  const [isSubmitting, setIsSubmitting] = useState(false);

  const {
    control,
    handleSubmit,
    setValue,
    formState: { errors },
  } = useForm<FormValues>({
    defaultValues: {
      first_name: "",
      last_name: "",
      email: "",
      password: "",
      user_type: "freelancer"
    }
  });

  const generateRandomPassword = () => {
    const length = 12;
    const uppercase = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
    const lowercase = 'abcdefghijklmnopqrstuvwxyz';
    const numbers = '0123456789';
    const symbols = '!@#$%^&*()_+[]{}|;:,.<>?';

    const getRandomChar = (characters: string) =>
      characters.charAt(Math.floor(Math.random() * characters.length));

    const password = [
      getRandomChar(uppercase),
      getRandomChar(lowercase),
      getRandomChar(numbers),
      getRandomChar(symbols),
    ];

    const allCharacters = uppercase + lowercase + numbers + symbols;
    for (let i = 4; i < length; i++) {
      password.push(getRandomChar(allCharacters));
    }

    return password.sort(() => Math.random() - 0.5).join('');
  };

  const handleCheckboxChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const isChecked = e.target.checked;
    setIsPasswordAutoGenerated(isChecked);
    if (isChecked) {
      setValue('password', generateRandomPassword());
    }
  };

  const onSubmit = async (data: FormValues) => {
    try {
      setIsSubmitting(true);
      const response = await apiCall(
        "/admin-dashboard/customers/create-customer/",
        "POST",
        data,
        null,
        {
          successMessage: "Customer created successfully",
          errorMessage: "Failed to create customer"
        }
      );
      
      if (response) {
        // Call the callback to refresh the table
        onCustomerAdded?.();
        // Close the drawer
        handleClose();
      }
    } catch (error) {
      console.error('Error creating customer:', error);
    } finally {
      setIsSubmitting(false);
    }
  };


  return (
    <Drawer
      anchor="right"
      open={open}
      onClose={handleClose}
      PaperProps={{
        sx: {
          width: "53%",
          padding: "32px 96px 32px 32px",
          backgroundColor: "white",
          height: "100vh",
          boxShadow: "0px 25px 50px -12px rgba(16, 24, 40, 0.25)",
          overflowY: "auto",
        },
      }}
      BackdropProps={{
        sx: {
          backgroundColor: "rgba(0, 0, 0, 0.5)",
        },
      }}
    >
      <form onSubmit={handleSubmit(onSubmit)}>
        <Box>
          <Stack gap={3}>
            <Typography variant="h2" letterSpacing={"0.4px"}>
              Add a Customer
            </Typography>
            <Divider
              sx={{
                borderColor: "rgba(240, 242, 245, 1)",
                marginBottom: "17px",
                marginRight: "-96px",
              }}
            />
            <Typography variant="caption" fontSize={14} color="#667185" ml={4}>
              To get started, fill out some basic information about who you are
              adding as a user.
            </Typography>
            <Box mt={-0.5} ml={4}>
              <Controller
                name="first_name"
                control={control}
                rules={{ required: "First name is required" }}
                render={({ field }) => (
                  <CustomTextField
                    {...field}
                    label="First Name"
                    placeholder="First Name"
                    fullWidth
                    error={!!errors.first_name}
                    helperText={errors.first_name?.message}
                  />
                )}
              />
            </Box>
            <Box mt={-0.5} ml={4}>
              <Controller
                name="last_name"
                control={control}
                rules={{ required: "Last name is required" }}
                render={({ field }) => (
                  <CustomTextField
                    {...field}
                    label="Last Name"
                    placeholder="Last Name"
                    fullWidth
                    error={!!errors.last_name}
                    helperText={errors.last_name?.message}
                  />
                )}
              />
            </Box>
            <Box mt={-0.5} ml={4}>
              <Controller
                name="email"
                control={control}
                rules={{
                  required: "Email is required",
                  pattern: {
                    value: /^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$/i,
                    message: "Invalid email address"
                  }
                }}
                render={({ field }) => (
                  <CustomTextField
                    {...field}
                    label="Email"
                    placeholder="email@gmail.com"
                    fullWidth
                    error={!!errors.email}
                    helperText={errors.email?.message}
                  />
                )}
              />
            </Box>
            <Box ml={4}>
              <Controller
                name="user_type"
                control={control}
                render={({ field }) => (
                  <CustomSelect
                    label="Role"
                    value={field.value}
                    onChange={(e: SelectChangeEvent) => field.onChange(e.target.value)}
                    options={Role}
                    placeholder="company"
                  />
                )}
              />
            </Box>
            <Box ml={4}>
              <CustomCheckbox
                label="Automatically Create Password"
                onChange={handleCheckboxChange}
              />
            </Box>
            <Box>
              <Typography
                variant="body2"
                sx={{ fontSize: "14px", color: "#344054" }}
                ml={4}
              >
                Passwords must be between 8 and 256 characters and use a
                combination of at least three of the following: uppercase
                letters, lowercase letters, numbers, and symbols.
              </Typography>
            </Box>
            <Box ml={4}>
              <Controller
                name="password"
                control={control}
                rules={{
                  required: "Password is required",
                  minLength: {
                    value: 8,
                    message: "Password must be at least 8 characters"
                  },
                  pattern: {
                    value: /^(?=.*[A-Z])(?=.*[0-9])(?=.*[!@#$%^&*])/,
                    message: "Password must contain at least one uppercase letter, one number, and one symbol"
                  }
                }}
                render={({ field }) => (
                  <PasswordField
                    {...field}
                    label="Password*"
                    required
                    error={!!errors.password}
                    helperText={errors.password?.message}
                  />
                )}
              />
            </Box>
          </Stack>
          <Box
            sx={{
              marginTop: "24px",
              display: "flex",
              justifyContent: "space-between",
              alignItems: "center",
            }}
            ml={4}
          >
            <CustomButton
              type="submit"
              variant="contained"
              fontSize="16px"
              padding="16px 24px"
              disabled={isSubmitting}
            >
              Add Customer
            </CustomButton>
            <CustomButton
              variant="contained"
              background="#F9FAFB"
              customColor="#344054"
              fontSize="16px"
              onClick={handleClose}
              padding="16px 24px"
              disabled={isSubmitting}
            >
              Cancel
            </CustomButton>
          </Box>
        </Box>
      </form>
    </Drawer>
  );
};

export default AddCustomerDrawer;